// answers — массив из 8 чисел (индекс выбранного варианта 0-7 для каждого вопроса).
export function scoreArchetypes(answers) {
  const counts = archetypes.map(() => 0);
  for (const choiceIndex of answers) {
    if (typeof choiceIndex === "number" && choiceIndex >= 0 && choiceIndex < archetypes.length) {
      counts[choiceIndex] += 1;
    }
  }

  const ranked = archetypes
    .map((a, i) => ({ ...a, count: counts[i] }))
    .sort((a, b) => b.count - a.count);

  const isMixed = ranked[0].count - ranked[1].count <= mixedProfileThreshold;

  return { ranked, counts, dominant: ranked[0], second: ranked[1], isMixed };
}
