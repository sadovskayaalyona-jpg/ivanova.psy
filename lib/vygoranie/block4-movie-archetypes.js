// variant: "primary" | "alt". Если у alt нет полного разбора (только note),
// используем primary как основу и подмешиваем character/source/note от alt —
// так UI всегда получает согласованную форму объекта.
export function getMovieArchetype(archetypeKey, variant = "primary") {
  const entry = movieArchetypes[archetypeKey];
  if (!entry) return null;

  if (variant === "alt" && entry.alt) {
    if (entry.alt.introParagraphs) {
      return { portrait: entry.portrait, ...entry.alt };
    }
    // alt — только краткая заметка, не полный профиль
    return {
      portrait: entry.portrait,
      character: entry.alt.character,
      source: entry.alt.source,
      note: entry.alt.note,
      introParagraphs: entry.primary.introParagraphs,
      strengths: entry.primary.strengths,
      shadow: entry.primary.shadow,
      growthAreas: entry.primary.growthAreas,
      harmonize: entry.primary.harmonize,
    };
  }

  return { portrait: entry.portrait, ...entry.primary };
}
